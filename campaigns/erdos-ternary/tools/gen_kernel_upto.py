#!/usr/bin/env python3
"""g003-C04: generate lean/ErdosTernary/CheckerKernelUpTo<k>.lean, a tier-A proof of `UpTo (2*3^k)`.

The tree of `CheckerKernel.exploreK` is cut into subtrees of at most LIMIT nodes. Each subtree root becomes one
theorem proved by `decide +kernel` (so kernel memory is bounded per declaration); nodes above the cut are assembled
with `CheckerKernel.exploreK_of_children`, the two roots with `checkK_of_roots`, and the result is turned into
`UpTo` by `checkK_sound`. All numerals are recomputed by the kernel (the defeq checks of the assembly), so this
script is untrusted: a wrong numeral makes `lake build` fail, it cannot make a false theorem.
Usage: python3 tools/gen_kernel_upto.py <k> [LIMIT] [K]"""
import pathlib, sys

sys.setrecursionlimit(100000)
k = int(sys.argv[1]); LIMIT = int(sys.argv[2]) if len(sys.argv) > 2 else 30000
K = int(sys.argv[3]) if len(sys.argv) > 3 else 64
N = 2 * 3 ** k; M = 3 ** K


def explore(fuel, q, r, m, g):
    """Mirror of exploreK; returns (result, subtree node count, children data or None if resolved here)."""
    if fuel == 0:
        return False, 1, None
    if N < r or m // q % 3 == 2 or (N < r + 2 * q and r <= 8):
        return True, 1, None
    g2 = g * g % M * g % M; m1 = m * g % M
    kids = [(fuel - 1, 3 * q, r, m, g2), (fuel - 1, 3 * q, r + 2 * q, m1, g2),
            (fuel - 1, 3 * q, r + 2 * (2 * q), m1 * g % M, g2)]
    res, cnt, sub = True, 1, []
    for kd in kids:
        rr, cc, ss = explore(*kd)
        res = res and rr; cnt += cc; sub.append((kd, cc, ss))
    return res, cnt, sub


out, stats = [], {"leaves": 0, "inner": 0, "max_leaf": 0}


def emit(name, node, cnt, sub):
    fuel, q, r, m, g = node
    stmt = f"exploreK {N} {M} {fuel} {q} {r} {m} {g} = true"
    if sub is None or cnt <= LIMIT:
        out.append(f"theorem {name} : {stmt} := by decide +kernel\n")
        stats["leaves"] += 1; stats["max_leaf"] = max(stats["max_leaf"], cnt)
        return
    for j, (kd, cc, ss) in enumerate(sub):
        emit(f"{name}_{j}", kd, cc, ss)
    out.append(f"theorem {name} : {stmt} :=\n  exploreK_of_children {N} {M} {fuel - 1} {q} {r} {m} {g} "
               f"{name}_0 {name}_1 {name}_2\n")
    stats["inner"] += 1


total = 0
roots = [(K, 1, 0, 1 % M, 4 % M), (K, 1, 1, 2 % M, 4 % M)]
for j, rt in enumerate(roots):
    res, cnt, sub = explore(*rt)
    assert res, "checker fails in Python mirror"
    total += cnt
    emit(f"n{k}_{j}", rt, cnt, sub)

hdr = f"""/- g003-C04 (generated by tools/gen_kernel_upto.py {k} {LIMIT} {K}; do not edit by hand).
Tier-A proof of `UpTo (2 * 3^{k})` with the kernel-friendly checker `CheckerKernel.exploreK`, depth bound {K}.
The tree ({total} nodes) is cut into {stats['leaves']} subtrees of at most {LIMIT} nodes (largest {stats['max_leaf']}),
each checked by `decide +kernel` in its own declaration; {stats['inner']} assembly steps use `exploreK_of_children`. -/
import ErdosTernary.CheckerKernel

namespace ErdosTernary

namespace CheckerKernel

"""
ftr = f"""
end CheckerKernel

/-- `UpTo (2 * 3^{k})`, checked by the kernel (`decide +kernel` on subtrees, tier A: no `native_decide`). -/
theorem upToK_{k} : UpTo (2 * 3 ^ {k}) :=
  CheckerKernel.checkK_sound (K := {K}) (CheckerKernel.checkK_of_roots _ _ CheckerKernel.n{k}_0 CheckerKernel.n{k}_1)

end ErdosTernary
"""
path = pathlib.Path(__file__).resolve().parent.parent / "lean" / "ErdosTernary" / f"CheckerKernelUpTo{k}.lean"
path.write_text(hdr + "\n".join(out) + ftr)
print(path, "nodes", total, stats)
